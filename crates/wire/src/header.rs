//! C header generation for build scripts.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;
use core::fmt::{self, Write as _};
use core::marker::PhantomData;

use crate::{ConstGroup, FieldDesc, WireStruct, fnv1a64};

const PREAMBLE: &str = "/* Generated by the `tracekit-wire` crate. Do not edit. */\n";

/// Fixed-width typedefs matching `<linux/types.h>`. Identical typedef redefinitions are valid C11,
/// so the header also coexists with `vmlinux.h`; defining `__WIRE_TYPES` beforehand skips them.
const TYPEDEFS: &str = "\
#ifndef __WIRE_TYPES
#define __WIRE_TYPES
typedef unsigned char __u8;
typedef signed char __s8;
typedef unsigned short __u16;
typedef signed short __s16;
typedef unsigned int __u32;
typedef signed int __s32;
typedef unsigned long long __u64;
typedef signed long long __s64;
#endif /* __WIRE_TYPES */
";

/// Renders the C header for a set of wire structs and constant groups.
///
/// Declarations appear in call order. C requires a struct to be complete before it is embedded,
/// so emit nested structs before the structs that contain them; [`structs`](Self::structs)
/// panics otherwise.
///
/// ```
/// tracekit_wire::wire! {
///     pub struct Pair {
///         pub a: u32,
///         pub b: u32,
///     }
/// }
///
/// let mut header = tracekit_wire::HeaderBuilder::new("PAIR_H");
/// header.structs::<Pair>();
/// let text = header.finish();
/// assert!(text.contains("_Static_assert(sizeof(struct pair) == 8"));
/// assert!(text.contains(&format!("#define PAIR_H_ABI_HASH {:#018x}ULL", header.abi_hash())));
/// ```
#[derive(Debug, Clone)]
pub struct HeaderBuilder {
    guard: String,
    body: String,
    structs: Vec<&'static str>,
}

impl HeaderBuilder {
    /// Starts a header whose include guard is `guard`; the ABI hash is defined as
    /// `<guard>_ABI_HASH`.
    ///
    /// # Panics
    ///
    /// If `guard` is not a C identifier.
    pub fn new(guard: &str) -> Self {
        assert!(
            is_c_identifier(guard),
            "header guard `{guard}` is not a C identifier"
        );
        Self {
            guard: guard.into(),
            body: String::new(),
            structs: Vec::new(),
        }
    }

    /// Emits the declaration of `T`, followed by `_Static_assert`s pinning its size, alignment
    /// and every field offset to the Rust layout.
    ///
    /// # Panics
    ///
    /// If `T` was already emitted, or embeds a wire struct that was not emitted before it.
    pub fn structs<T: WireStruct>(&mut self) -> &mut Self {
        let name = T::C_NAME;
        assert!(
            !self.structs.contains(&name),
            "struct {name} is emitted twice"
        );
        for field in T::FIELDS {
            if let Some(nested) = field.c_type.strip_prefix("struct ") {
                assert!(
                    self.structs.contains(&nested),
                    "struct {name} embeds struct {nested}, which must be emitted first"
                );
            }
        }
        self.structs.push(name);
        self.append(StructDecl::<T>(PhantomData));
        self
    }

    /// Emits `#define NAME VALUE` for each constant of `group`.
    pub fn consts(&mut self, group: &ConstGroup) -> &mut Self {
        self.append(ConstDefines(group));
        self
    }

    /// Renders the complete header: include guard, fixed-width typedefs, the emitted declarations
    /// and `#define <GUARD>_ABI_HASH`.
    pub fn finish(&self) -> String {
        let Self { guard, body, .. } = self;
        format!(
            "{PREAMBLE}#ifndef {guard}\n#define {guard}\n\n{TYPEDEFS}\n{body}\
             #define {guard}_ABI_HASH {hash:#018x}ULL\n\n#endif /* {guard} */\n",
            hash = self.abi_hash(),
        )
    }

    /// FNV-1a 64 of the emitted declarations (structs, static asserts and constants, in call
    /// order). The include guard and fixed preamble are excluded, so the hash identifies the ABI
    /// alone.
    pub fn abi_hash(&self) -> u64 {
        fnv1a64(self.body.as_bytes())
    }

    fn append(&mut self, decl: impl fmt::Display) {
        // Writing to a `String` cannot fail, and the declaration renderers never return errors.
        let _ = write!(self.body, "{decl}");
    }
}

fn is_c_identifier(s: &str) -> bool {
    let mut bytes = s.bytes();
    bytes
        .next()
        .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
        && bytes.all(|b| b.is_ascii_alphanumeric() || b == b'_')
}

/// C name of a field: raw identifiers lose their `r#` prefix.
fn field_name(field: &FieldDesc) -> &'static str {
    field.name.strip_prefix("r#").unwrap_or(field.name)
}

struct StructDecl<T>(PhantomData<T>);

impl<T: WireStruct> fmt::Display for StructDecl<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let name = T::C_NAME;
        writeln!(f, "struct {name} {{")?;
        for field in T::FIELDS {
            write!(f, "\t{} {}", field.c_type, field_name(field))?;
            for dim in field.dims {
                write!(f, "[{dim}]")?;
            }
            f.write_str(";\n")?;
        }
        f.write_str("};\n")?;

        writeln!(
            f,
            "_Static_assert(sizeof(struct {name}) == {size}, \
             \"sizeof(struct {name}) differs from Rust\");",
            size = T::SIZE,
        )?;
        writeln!(
            f,
            "_Static_assert(_Alignof(struct {name}) == {align}, \
             \"_Alignof(struct {name}) differs from Rust\");",
            align = T::ALIGN,
        )?;
        for field in T::FIELDS {
            let field_name = field_name(field);
            writeln!(
                f,
                "_Static_assert(__builtin_offsetof(struct {name}, {field_name}) == {offset}, \
                 \"offsetof(struct {name}, {field_name}) differs from Rust\");",
                offset = field.offset,
            )?;
        }
        f.write_str("\n")
    }
}

struct ConstDefines<'a>(&'a ConstGroup);

impl fmt::Display for ConstDefines<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "/* {} */", self.0.name)?;
        for c in self.0.consts {
            writeln!(f, "#define {} {}", c.name, c.value)?;
        }
        f.write_str("\n")
    }
}
