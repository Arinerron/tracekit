#[test]
fn header_frames_declarations_with_guard_typedefs_and_hash() {
    let header = builder();
    let text = header.finish();

    assert!(text.starts_with("/* Generated by the `wire` crate. Do not edit. */\n"));
    assert!(text.contains("#ifndef TRACEKIT_TEST_WIRE_H\n#define TRACEKIT_TEST_WIRE_H\n"));
    assert!(text.contains("#ifndef __WIRE_TYPES\n#define __WIRE_TYPES\n"));
    assert!(text.contains("typedef unsigned long long __u64;\n"));
    assert!(text.ends_with("#endif /* TRACEKIT_TEST_WIRE_H */\n"));

    let hash_line = format!(
        "#define TRACEKIT_TEST_WIRE_H_ABI_HASH 0x{:016x}ULL\n",
        header.abi_hash()
    );
    assert!(text.contains(&hash_line), "{text}");
    // Typedefs precede every declaration; the hash comes after all of them.
    let typedefs = text.find("#endif /* __WIRE_TYPES */").unwrap();
    assert!(typedefs < text.find("struct ev_header {").unwrap());
    assert!(text.find("#define ALL_FLAGS").unwrap() < text.find(&hash_line).unwrap());
}

#[test]
fn abi_hash_covers_declarations_only() {
    let text = builder().finish();
    let start = text.find("struct ev_header {").unwrap();
    let end = text.find("#define TRACEKIT_TEST_WIRE_H_ABI_HASH").unwrap();
    assert_eq!(builder().abi_hash(), fnv1a64(&text.as_bytes()[start..end]));

    let mut renamed = HeaderBuilder::new("OTHER_GUARD");
    renamed
        .structs::<EvHeader>()
        .structs::<ExecEvent>()
        .structs::<ConnEvent>()
        .consts(&ABI_CONSTS);
    assert_eq!(renamed.abi_hash(), builder().abi_hash());
}

mod changed_type {
    wire::wire! {
        /// `EvHeader` with `pid` signed: same layout, different C type.
        pub struct EvHeader {
            pub kind: u32,
            pub pid: i32,
            pub ts_ns: u64,
        }
    }
}

mod changed_name {
    wire::wire! {
        /// `EvHeader` with `pid` renamed.
        pub struct EvHeader {
            pub kind: u32,
            pub tgid: u32,
            pub ts_ns: u64,
        }
    }
}

mod changed_layout {
    wire::wire! {
        /// `EvHeader` with `ts_ns` first.
        pub struct EvHeader {
            pub ts_ns: u64,
            pub kind: u32,
            pub pid: u32,
        }
    }
}

#[test]
fn abi_hash_changes_when_a_field_changes() {
    fn hash<T: WireStruct>() -> u64 {
        let mut header = HeaderBuilder::new(GUARD);
        header.structs::<T>();
        header.abi_hash()
    }

    let original = hash::<EvHeader>();
    assert_eq!(original, hash::<EvHeader>());
    let variants = [
        hash::<changed_type::EvHeader>(),
        hash::<changed_name::EvHeader>(),
        hash::<changed_layout::EvHeader>(),
    ];
    for variant in variants {
        assert_ne!(variant, original);
    }
}

#[test]
fn abi_hash_changes_when_a_constant_changes() {
    mod changed {
        wire::wire_consts! {
            pub group ABI_CONSTS;
            pub const MAX_ENTRIES: u32 = 2048;
            pub const EV_EXEC: u8 = 1;
            pub const MIN_DELTA: i64 = -3;
            pub const ALL_FLAGS: u64 = u64::MAX;
        }
    }

    let mut header = HeaderBuilder::new(GUARD);
    header
        .structs::<EvHeader>()
        .structs::<ExecEvent>()
        .structs::<ConnEvent>()
        .consts(&changed::ABI_CONSTS);
    assert_ne!(header.abi_hash(), builder().abi_hash());
}

