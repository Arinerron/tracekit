#[test]
fn debug_prints_byte_arrays_compactly() {
    let mut comm = [0; 16];
    comm[..4].copy_from_slice(b"bash");
    let event = ExecEvent {
        hdr: EvHeader {
            kind: 1,
            pid: 42,
            ts_ns: 7,
        },
        comm,
        argv_len: 3,
        _pad: [0; 6],
    };
    assert_eq!(
        format!("{event:?}"),
        "ExecEvent { hdr: EvHeader { kind: 1, pid: 42, ts_ns: 7 }, comm: b\"bash\", \
         argv_len: 3, _pad: b\"\" }"
    );

    let mut addrs = [[0; 20]; 8];
    addrs[1][..2].copy_from_slice(&[0x7f, b'"']);
    let conn = ConnEvent {
        hdr: event.hdr,
        addrs,
        count: -1,
        _pad: 0,
    };
    let debug = format!("{conn:?}");
    assert!(
        debug.contains("addrs: [b\"\", b\"\\x7f\\\"\", b\"\", b\"\", b\"\", b\"\", b\"\", b\"\"]"),
        "{debug}"
    );
    assert!(debug.contains("count: -1"), "{debug}");
}

/// Runs `clang -target bpfel -fsyntax-only` on `source`; `None` if clang is not installed.
fn clang_accepts(source: &str) -> Option<bool> {
    let mut child = match Command::new("clang")
        .args([
            "-target",
            "bpfel",
            "-fsyntax-only",
            "-Wall",
            "-Werror",
            "-x",
            "c",
            "-",
        ])
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()
    {
        Ok(child) => child,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => return None,
        Err(err) => panic!("failed to run clang: {err}"),
    };
    child
        .stdin
        .take()
        .unwrap()
        .write_all(source.as_bytes())
        .unwrap();
    let output = child.wait_with_output().unwrap();
    if !output.status.success() {
        eprintln!("{}", String::from_utf8_lossy(&output.stderr));
    }
    Some(output.status.success())
}

#[test]
fn clang_accepts_generated_header() {
    let header = builder().finish();
    let Some(accepted) = clang_accepts(&header) else {
        eprintln!("clang not found; skipping");
        return;
    };
    assert!(accepted, "{header}");

    // vmlinux.h spells the same typedefs differently; identical redefinitions must be accepted.
    let with_vmlinux_typedefs = format!(
        "typedef unsigned char __u8;\ntypedef short int __s16;\n\
         typedef unsigned int __u32;\ntypedef long long unsigned int __u64;\n{header}"
    );
    assert_eq!(clang_accepts(&with_vmlinux_typedefs), Some(true));
}

#[test]
fn clang_rejects_layout_drift() {
    let header = builder().finish();
    let drifted = header.replace(
        "__builtin_offsetof(struct conn_event, count) == 176",
        "__builtin_offsetof(struct conn_event, count) == 172",
    );
    assert_ne!(drifted, header);
    match clang_accepts(&drifted) {
        Some(accepted) => assert!(!accepted, "offset drift must fail to compile"),
        None => eprintln!("clang not found; skipping"),
    }
}
